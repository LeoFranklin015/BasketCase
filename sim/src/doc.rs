//! `docs/simulation.md`: what was simulated, key results, a table per scenario, assumptions and
//! caveats. Every number in it is formatted from `Params`, the scenario constants or the results,
//! so the drift check also catches the prose going stale.

use crate::params::Params;
use crate::report::{ppm_pct, whole_units, DayOut, ScenarioOut, SimOut, JSON_PATH};
use crate::scenario::{
    ARB_CHUNK_BPS, ARB_MAX_ROUNDS, BASKET_DAILY_VOL_PPM, CHALLENGE_BUDGET_BPS,
    CHALLENGE_MARGIN_PCT, CHALLENGE_PARTS, CHALLENGE_QUIET_HOURS, DAYS, DEFEND_DELAY_HOURS,
    DEFEND_PPM, DEFEND_SIZE_PCT, EPOCH_BURN_CAP_BPS, RETAIL_SIZES_BU, SEAT_WEIGHT_BPS,
    SOLVER_CUT_BPS, TAKE_PROFIT_PCT, TAKE_PROFIT_PPM, WHALE_DUMP_HOURS,
};
use std::fmt::Write as _;

const SUMMARY_DAYS: [usize; 5] = [0, 15, 30, 45, 60];

/// A whole number with thousands separators, e.g. "1,073,000,000".
fn thousands(x: f64) -> String {
    let digits = format!("{x:.0}");
    let (sign, digits) = digits.split_at(if digits.starts_with('-') { 1 } else { 0 });
    let mut out = String::new();
    for (i, ch) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i) % 3 == 0 {
            out.push(',');
        }
        out.push(ch);
    }
    format!("{sign}{out}")
}

/// Tokens in millions, e.g. "512.3M".
fn millions(x: f64) -> String {
    format!("{:.1}M", x / 1e6)
}

/// BU per token, written as BU per 1M tokens.
fn per_million(x: f64) -> String {
    format!("{:.2}", x * 1e6)
}

/// Basis points as a percentage, e.g. 300 -> "3%", 50 -> "0.5%".
fn bps(v: u128) -> String {
    format!("{}%", v as f64 / 100.0)
}

fn pct_change(from: f64, to: f64) -> String {
    format!("{:+.0}%", (to / from - 1.0) * 100.0)
}

fn last_day(s: &ScenarioOut) -> &DayOut {
    &s.days[DAYS as usize]
}

fn scenario<'a>(out: &'a SimOut, id: &str) -> &'a ScenarioOut {
    out.scenarios.iter().find(|s| s.id == id).expect("scenario exists")
}

pub(crate) fn markdown(p: &Params, out: &SimOut) -> String {
    let mut md = String::new();
    let w = &mut md;
    let seeds = out.params.seeds;
    let _ = writeln!(w, "# Simulation: {DAYS} days, {} scenarios, {seeds} seeds each\n", out.scenarios.len());
    let _ = writeln!(
        w,
        "Generated by `cargo run -p sim --release`, which also writes `{JSON_PATH}` (the data behind \
         the `/sim` page). Do not edit this file by hand: `cargo run -p sim --release -- --check` \
         fails when it differs from a fresh run.\n"
    );
    let _ = writeln!(w, "## What is simulated\n");
    let _ = writeln!(
        w,
        "One coin, from its fair-launch window to day {DAYS}, in hourly steps ({} steps). Each \
         scenario runs with {seeds} seeds; every number below is the median across seeds unless it \
         says otherwise (`sim.json` also has p10 and p90 for every metric and day). The mechanism is \
         not re-implemented: every buy, sell, burn, graduation, pool trade and redeem calls the same \
         `curve-math` functions as the coin contract, on the same raw 1e18-scaled integers. The one \
         piece of contract arithmetic outside `curve-math`, the fee on a buy capped at graduation, \
         mirrors `contracts/coin/src/trade.rs`. After every action the simulator checks that the BU \
         the coin owes (reserve + surplus + owed fees + pool) never exceeds the BU its vault holds; \
         a violation aborts the run.\n",
        DAYS * 24
    );
    let _ = writeln!(w, "Mechanism parameters (from `constants.json`):\n");
    let _ = writeln!(
        w,
        "- Curve: {} virtual BU, {} virtual tokens, graduation at {} BU of reserve ({} tokens sold).",
        thousands(whole_units(p.curve.x0)),
        thousands(whole_units(p.curve.y0)),
        thousands(whole_units(p.curve.grad_reserve)),
        millions(whole_units(p.tokens_at_graduation()))
    );
    let [creator, vault, protocol] = p.split_bps;
    let _ = writeln!(
        w,
        "- Trade fee {}, split creator {} / vault {} / protocol {}. The vault share goes to the \
         surplus before graduation and to the reserve after.",
        bps(p.fee_bps),
        bps(creator),
        bps(vault),
        bps(protocol)
    );
    let _ = writeln!(
        w,
        "- Graduation puts {} of the backing in the pool; redeems pay `reserve / supply` less {}, \
         which stays in the reserve.",
        bps(p.pool_share_bps),
        bps(p.redeem_fee_bps)
    );
    let _ = writeln!(
        w,
        "- A challenge must burn at least {} of its slot's value and beat the defenders; epochs \
         are {} days.\n",
        bps(p.challenge_min_bps),
        p.epoch_hours / 24
    );
    let _ = writeln!(
        w,
        "**Floor.** Before graduation the floor is `P0 + s` (the curve's lowest price plus the surplus \
         per token): no sell pays less per token, before the fee. After graduation it is \
         `reserve / supply`, where supply includes the pool's tokens. **Price** is the price of the \
         next token: the curve price plus `s`, or the pool's spot price after graduation.\n"
    );

    key_results(w, p, out);
    scenario_tables(w, p, out);
    assumptions(w, p, out);
    caveats(w, p);
    format_note(w);
    md
}

/// One line per scenario, every number read from the medians.
fn key_results(w: &mut String, p: &Params, out: &SimOut) {
    let (steady, pump, war, grad) = (
        scenario(out, "steady"),
        scenario(out, "pump-and-dump"),
        scenario(out, "challenge-war"),
        scenario(out, "graduation"),
    );
    let _ = writeln!(w, "## Key results (medians across seeds)\n");

    let (a, b) = (&steady.days[0], last_day(steady));
    let _ = writeln!(
        w,
        "- **Steady growth:** supply grows from {} to {} tokens as buyers arrive. Fees alone lift the \
         floor from {} to {} BU per 1M tokens ({}), while the price climbs from {} to {}, so the floor \
         ends at {:.1}% of the price.",
        millions(a.supply.median),
        millions(b.supply.median),
        per_million(a.floor_bu.median),
        per_million(b.floor_bu.median),
        pct_change(a.floor_bu.median, b.floor_bu.median),
        per_million(a.price_bu.median),
        per_million(b.price_bu.median),
        b.floor_pct_of_price.median
    );

    let dump_end = pump.agents.whale_dump_days[1] as usize;
    let peak = pump.days[..=dump_end]
        .iter()
        .max_by(|x, y| x.price_bu.median.total_cmp(&y.price_bu.median))
        .expect("days");
    let falls = pump.days.windows(2).any(|d| d[1].floor_bu.median < d[0].floor_bu.median);
    let _ = writeln!(
        w,
        "- **Pump and dump:** the price peaks at {} on day {} and is {} by day {DAYS} ({}); circulating \
         supply drops from a peak of {} to {} as holders sell back to the curve. The floor {} \
         ({} to {}): sells pay out the curve and their own share of the surplus, never other holders' \
         share.",
        per_million(peak.price_bu.median),
        peak.day,
        per_million(last_day(pump).price_bu.median),
        pct_change(peak.price_bu.median, last_day(pump).price_bu.median),
        millions(pump.days.iter().map(|d| d.circulating.median).fold(0.0, f64::max)),
        millions(last_day(pump).circulating.median),
        if falls { "dips on some days but ends higher" } else { "never falls" },
        per_million(pump.days[0].floor_bu.median),
        per_million(last_day(pump).floor_bu.median)
    );

    let (ws, ss) = (last_day(war), last_day(steady));
    let st = &war.stats;
    let _ = writeln!(
        w,
        "- **Challenge war:** with the same buyers as the steady scenario, weekly challenge and defend \
         burns remove {} tokens ({:.1}% of circulating supply) by day {DAYS}. The day-{DAYS} floor is {} \
         against {} without burns ({}), and {:.1}% of the price against {:.1}%. That is after {} winning \
         challenges per run, each costing the vault a {} to {} solver cut on the seat.",
        millions(ws.burned_total.median),
        ws.burned_total.median / ws.circulating.median * 100.0,
        per_million(ws.floor_bu.median),
        per_million(ss.floor_bu.median),
        pct_change(ss.floor_bu.median, ws.floor_bu.median),
        ws.floor_pct_of_price.median,
        ss.floor_pct_of_price.median,
        st.swaps_per_run.median,
        bps(SOLVER_CUT_BPS.0 as u128),
        bps(SOLVER_CUT_BPS.1 as u128)
    );
    if let (Some(min), Some(burn)) = (st.epoch_min_challenge_pct_of_supply, st.epoch_burn_pct_of_supply) {
        let _ = writeln!(
            w,
            "- **The challenge minimum binds.** A winning challenge must burn at least {} of the seat's \
             value, which here is {}% of circulating supply (p10 {}%, p90 {}%). Challengers aiming just \
             past it, plus defenders answering, burn {}% of supply in a median epoch (p10 {}%), so the \
             {} weekly cap this scenario sets is reached in most epochs. A challenge burning less than \
             {}% of supply would have failed in at least 90% of these epochs.",
            bps(p.challenge_min_bps),
            min.median,
            min.p10,
            min.p90,
            burn.median,
            burn.p10,
            bps(EPOCH_BURN_CAP_BPS),
            min.p10
        );
    }

    let g = &grad.stats;
    let after = grad.days.iter().find(|d| d.graduated_share >= 1.0).unwrap_or(last_day(grad));
    let tightest = grad.days[after.day as usize..]
        .iter()
        .max_by(|x, y| x.floor_pct_of_price.median.total_cmp(&y.floor_pct_of_price.median))
        .expect("days");
    let _ = writeln!(
        w,
        "- **Graduation:** {} of {} runs graduate, on day {} (median). The floor jumps from `P0 + s` to \
         `reserve / supply`: {} on day {}, the first day every run has graduated. When demand fades the \
         pool price falls toward the floor (on day {} the floor is {:.1}% of the price), sells start \
         paying out by redeeming because the matching path pays whichever is larger, and redeems burn \
         {} tokens by day {DAYS} while the floor rises to {}. Holders bought high in the run-up: on day \
         {} the average cost across all holders is {}, so the floor covers {:.0}% of what the average \
         holder paid.",
        g.graduated_runs,
        g.seeds,
        g.graduation_day.map(|b| b.median.to_string()).unwrap_or_else(|| "-".into()),
        per_million(after.floor_bu.median),
        after.day,
        tightest.day,
        tightest.floor_pct_of_price.median,
        millions(last_day(grad).redeemed_total.median),
        per_million(last_day(grad).floor_bu.median),
        tightest.day,
        per_million(tightest.holders_avg_cost_bu.median),
        tightest.floor_bu.median / tightest.holders_avg_cost_bu.median * 100.0
    );
    let _ = writeln!(w);
}

fn scenario_tables(w: &mut String, p: &Params, out: &SimOut) {
    let _ = writeln!(w, "## Scenarios and results\n");
    let _ = writeln!(
        w,
        "Prices are in BU per 1M tokens (at launch 1 BU = ${}, so 4.66 means ${} per million \
         tokens). Burned counts challenge and defend burns; redeemed counts tokens burned by \
         redeems; avg cost is the holders' average cost per 1M tokens, fees included.\n",
        whole_units(p.bu_usd_e18),
        4.66 * whole_units(p.bu_usd_e18)
    );
    for s in &out.scenarios {
        let _ = writeln!(w, "### {}\n", s.title);
        let _ = writeln!(w, "{}\n", s.description);
        let _ = writeln!(
            w,
            "| Day | Supply | Circulating | Price | Floor | Floor % of price | Floor p10 to p90 | Vault BU | Burned | Redeemed | Avg cost |"
        );
        let _ = writeln!(w, "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |");
        for &d in &SUMMARY_DAYS {
            let x = &s.days[d];
            let _ = writeln!(
                w,
                "| {} | {} | {} | {} | {} | {:.1}% | {} to {} | {} | {} | {} | {} |",
                x.day,
                millions(x.supply.median),
                millions(x.circulating.median),
                per_million(x.price_bu.median),
                per_million(x.floor_bu.median),
                x.floor_pct_of_price.median,
                per_million(x.floor_bu.p10),
                per_million(x.floor_bu.p90),
                thousands(x.vault_bu.median),
                millions(x.burned_total.median),
                millions(x.redeemed_total.median),
                per_million(x.holders_avg_cost_bu.median),
            );
        }
        let st = &s.stats;
        let mut notes = vec![format!(
            "graduated in {} of {} runs{}",
            st.graduated_runs,
            st.seeds,
            st.graduation_day
                .map(|b| format!(" (median day {}, p10 to p90 days {} to {})", b.median, b.p10, b.p90))
                .unwrap_or_default()
        )];
        if let (Some(b), Some(min)) = (st.epoch_burn_pct_of_supply, st.epoch_min_challenge_pct_of_supply) {
            notes.push(format!(
                "{} epochs closed per run, {} seat swaps per run (median, p10 {} to p90 {}); burns per \
                 epoch {}% of supply (median; p10 {}%, p90 {}%), against a challenge minimum worth \
                 {}% of supply (median; p10 {}%, p90 {}%)",
                st.epochs_closed_per_run,
                st.swaps_per_run.median,
                st.swaps_per_run.p10,
                st.swaps_per_run.p90,
                b.median,
                b.p10,
                b.p90,
                min.median,
                min.p10,
                min.p90
            ));
        }
        if st.graduated_runs > 0 {
            notes.push(format!(
                "after graduation, {} sells per run were paid by redeeming and the arbitrageur \
                 bought and redeemed {} times (medians)",
                st.redeem_sells_per_run.median, st.arb_redeems_per_run.median
            ));
        }
        notes.push(format!(
            "{} buys and {} sells per run (medians)",
            st.buys_per_run.median, st.sells_per_run.median
        ));
        let _ = writeln!(w, "\nPer run: {}.\n", notes.join("; "));
    }
}

fn assumptions(w: &mut String, p: &Params, out: &SimOut) {
    let (steady, pump) = (scenario(out, "steady"), scenario(out, "pump-and-dump"));
    let sizes: Vec<String> = RETAIL_SIZES_BU.iter().map(|(bu, pct)| format!("{bu} ({pct}%)")).collect();
    let mean = RETAIL_SIZES_BU.iter().map(|&(bu, pct)| bu as f64 * pct as f64).sum::<f64>() / 100.0;
    let tps: Vec<String> = TAKE_PROFIT_PCT.iter().map(|t| format!("{t}%")).collect();
    let epoch_days = p.epoch_hours / 24;
    let closes = DAYS as u64 * 24 / p.epoch_hours;
    let _ = writeln!(w, "## Assumptions\n");
    let _ = writeln!(w, "Every behaviour is a small rule with a fixed number, so each result can be traced back. The numbers are also in `sim.json` under `params` and each scenario's `agents`.\n");
    let _ = writeln!(w, "**Time and randomness**");
    let _ = writeln!(w, "- Hourly steps for {DAYS} days. Four seeded ChaCha8 streams per seed: arrivals (who arrives when, ticket sizes, each holder's habits), decisions (daily sell rolls), rituals, and the basket. Seed *n* gets the same basket path in every scenario, and the steady and challenge-war scenarios get the same buyers, so their difference is the rituals.");
    let _ = writeln!(w, "- All model arithmetic is integer; the files are byte-identical on any machine.\n");
    let _ = writeln!(w, "**Value of a BU**");
    let _ = writeln!(w, "- 1 BU = ${} at launch (`launch.bu_usd_default` in `constants.json`; a real coin picks its own at launch), so graduation ({} BU of reserve) means about ${} raised. Agents act in BU, so this value only scales the USD columns.", whole_units(p.bu_usd_e18), thousands(whole_units(p.curve.grad_reserve)), thousands(whole_units(p.curve.grad_reserve) * whole_units(p.bu_usd_e18)));
    let _ = writeln!(w, "- The basket's USD value follows a random walk with {}% daily volatility and no drift (an integer approximation of a normal draw). It moves only the USD columns in `sim.json`; agents trade in BU and do not react to it.\n", ppm_pct(BASKET_DAILY_VOL_PPM as u32));
    let _ = writeln!(w, "**Agents**");
    let _ = writeln!(w, "- Fair-launch window: every launch deposit pays its fee, the nets are pooled into one curve buy, and the tokens are split pro rata.");
    let _ = writeln!(w, "- Retail buyers arrive at random (60 one-minute slots per hour, each a buyer with probability rate / 1,440). Ticket sizes in BU: {}; mean {mean}.", sizes.join(", "));
    let _ = writeln!(w, "- Each retail holder checks once a day at its own hour and, in this order: churns out (sells everything) with the scenario's daily chance; or, if the price is at its take-profit multiple of its average cost ({}, drawn per holder), sells half with probability {}%; or, if the price is the scenario's panic threshold below its cost, panic-sells everything with the scenario's daily chance.", tps.join(", "), ppm_pct(TAKE_PROFIT_PPM));
    let _ = writeln!(w, "- Holders compare the next-token price with their average cost, fees included (average-cost method).");
    let _ = writeln!(w, "- Early holders (steady, challenge war) join the fair launch with {} BU each and never sell.", steady.agents.early_holder_bu);
    let _ = writeln!(w, "- Whales (pump and dump) join the fair launch with {} to {} BU each and sell everything in {} hourly chunks, starting at a random hour between day {} and day {}.", thousands(pump.agents.whale_bu[0] as f64), thousands(pump.agents.whale_bu[1] as f64), WHALE_DUMP_HOURS, pump.agents.whale_dump_days[0], pump.agents.whale_dump_days[1]);
    let _ = writeln!(w, "- Fees owed to the creator and the protocol are claimed at the end of each day.\n");
    let _ = writeln!(w, "**Rituals (challenge war)**");
    let _ = writeln!(w, "- The basket is one anchored asset and one {} seat; challengers always target the seat.", bps(SEAT_WEIGHT_BPS));
    let _ = writeln!(w, "- Each {epoch_days}-day epoch the challengers aim for {}% to {}% of the challenge minimum as it stands at the epoch's start. They turn that into tokens at the current burn value, clamp it to {} to {} of circulating supply, and burn it in {} or {} equal parts at random hours (none in the epoch's last {CHALLENGE_QUIET_HOURS} hours).", CHALLENGE_MARGIN_PCT.0, CHALLENGE_MARGIN_PCT.1, bps(CHALLENGE_BUDGET_BPS.0), bps(CHALLENGE_BUDGET_BPS.1), CHALLENGE_PARTS.0, CHALLENGE_PARTS.1);
    let _ = writeln!(w, "- Defenders answer each challenge burn with probability {}%, {} to {} hours later, burning {}% to {}% of its size.", ppm_pct(DEFEND_PPM), DEFEND_DELAY_HOURS.0, DEFEND_DELAY_HOURS.1, DEFEND_SIZE_PCT.0, DEFEND_SIZE_PCT.1);
    let _ = writeln!(w, "- All burns in an epoch are capped at {} of supply at the epoch's start, first come first served: once the cap is reached, later burns that epoch, from either side, are cut. The biggest bag on each side burns, out of the early holders' bags.", bps(EPOCH_BURN_CAP_BPS));
    let _ = writeln!(w, "- At the epoch's close the challenge wins if its tally beats the defense and is at least the challenge minimum ({} of the seat's share of the vault). A win costs the vault the solver's cut: {} to {} of the seat's value, drawn per swap.", bps(p.challenge_min_bps), bps(SOLVER_CUT_BPS.0 as u128), bps(SOLVER_CUT_BPS.1 as u128));
    let _ = writeln!(w, "- Where that loss lands: before graduation it comes out of the surplus, not the reserve. The reserve is the curve's own position, and cutting it while `sold` stays the same breaks `x * y >= k`: `Curve::sell` would underflow on a small sell or hand the whole cut to one seller. Taking it all from the surplus is the cautious choice. It lowers `s`, and so the floor, more than a cut spread pro rata over reserve and surplus would. After graduation the loss is shared by the reserve and the pool pro rata.");
    let _ = writeln!(w, "- {closes} epochs close in {DAYS} days; the next one starts and is cut off at day {DAYS} before it closes.\n");
    let _ = writeln!(w, "**After graduation**");
    let _ = writeln!(w, "- Buys go through the pool. A sell pays the larger of the pool's output after the fee and the redeem value after the {} redeem fee.", bps(p.redeem_fee_bps));
    let _ = writeln!(w, "- One agent the brief did not list: an arbitrageur. Every hour, while buying {} of the pool's BU and redeeming the tokens pays more than it costs, it does so (up to {ARB_MAX_ROUNDS} times an hour). It stands for anyone who would take that free money, and it keeps the pool price from staying below the floor. It trades rarely (see the per-run counts above).\n", bps(ARB_CHUNK_BPS));
}

fn caveats(w: &mut String, p: &Params) {
    let _ = writeln!(w, "## Caveats\n");
    let _ = writeln!(w, "- **Behaviour is assumed, not fitted.** Arrival rates, ticket sizes and selling rules are simple guesses, set so each scenario tells its story; no rule was calibrated against real launchpad data. Treat the levels as illustrations and the comparisons between scenarios as the result.");
    let _ = writeln!(w, "- **The basket is one number.** The BU's USD value is a single random walk; the agents never react to it, and there is no basket crash scenario here.");
    let _ = writeln!(w, "- **No adversarial trading beyond the arbitrageur.** No sandwiching, no sniping (the fair-launch window removes the first-block edge), no wash trading to farm the creator fee.");
    let _ = writeln!(w, "- **The swap is a fixed haircut.** A winning challenge is modelled as a {} to {} BU loss, not as a Dutch auction with real bidders; the replacement asset's later performance is not modelled.", bps(SOLVER_CUT_BPS.0 as u128), bps(SOLVER_CUT_BPS.1 as u128));
    let _ = writeln!(w, "- **The burn cap shapes the war.** The challenge minimum ({} of the seat's value) costs more than half of the {} weekly cap in tokens, so the cap is reached in most epochs, and its first-come order partly decides who wins a contested week. A larger cap means more burning and a higher floor; a smaller one means no swaps at all.", bps(p.challenge_min_bps), bps(EPOCH_BURN_CAP_BPS));
    let _ = writeln!(w, "- **Factions are tiny.** Three challengers and three defenders burning from bags they got at launch.");
    let _ = writeln!(w, "- **The floor before graduation is conservative.** `P0 + s` is what the last seller is guaranteed; the average backing per token, `(reserve + surplus) / circulating`, is higher.");
    let _ = writeln!(w, "- **Percentile bands are per metric.** The median price and the median floor on a day can come from different seeds.\n");
}

fn format_note(w: &mut String) {
    let _ = writeln!(w, "## `sim.json` format\n");
    let _ = writeln!(w, "`{{ generated_by, params, scenarios: [{{ id, title, description, agents, stats, days }}] }}`. Each entry in `days` is `{{ day, supply, circulating, price_bu, floor_bu, surplus_per_token, vault_bu, burned_total, redeemed_total, holders_avg_cost_bu, floor_pct_of_price, bu_usd, price_usd, floor_usd, mode, graduated_share }}`. Every metric except `day`, `mode` and `graduated_share` is `{{ p10, median, p90 }}` across seeds. Amounts are whole tokens or whole BU (not raw 1e18 units); prices are BU (or USD) per token; `floor_pct_of_price` is a percentage. `mode` is the mode most seeds are in that day, and `graduated_share` the fraction of seeds in Index mode. Day 0 is the moment the fair-launch window settles; day *d* is the end of the *d*-th day.");
}

